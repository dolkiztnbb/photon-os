#ifndef ATA_H
#define ATA_H

/*
 * drivers/ata.c — IDE/PATA диски (PIO, LBA28/LBA48) и ATAPI CD/DVD-приводы.
 *
 * Находит IDE-контроллеры на шине PCI (класс 01h / подкласс 01h) — как в
 * legacy-режиме (порты 1F0h/3F6h и 170h/376h), так и в native-режиме
 * (базы из BAR0..BAR3), опрашивает master/slave на каждом канале и
 * регистрирует найденное в реестре блочных устройств:
 *   "hd0".."hd3" — диски ATA (512-байтные сектора, чтение и запись),
 *   "cd0".."cd3" — приводы ATAPI (2048-байтные блоки, только чтение;
 *                  наружу отдаются 512-байтными секторами).
 * Работает без прерываний (polling), IRQ контроллера маскируются битом nIEN.
 */

void ata_init(void);

#endif
