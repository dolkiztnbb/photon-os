#ifndef USB_H
#define USB_H

#include <libc/stdint>
#include <drivers/blockdev.h>

/* Ищет USB-флешку на контроллерах xHCI (USB 3.x) и EHCI (USB 2.0) — сначала
 * на всех xHCI, потом на всех EHCI, в корневых портах и за USB-хабами (в т.ч.
 * встроенным RMH чипсетов Intel) — и регистрирует её как "usb0".
 *
 * accept(dev) вызывается для каждой найденной флешки (dev уже умеет читать
 * сектора). Если accept == NULL или вернул не 0, флешка регистрируется, и
 * контроллер остаётся за ядром. Контроллер, на котором подходящей флешки
 * нет, останавливается (порты EHCI отдаются companion-контроллерам UHCI/OHCI,
 * если они есть; BIOS его обратно не получает), и поиск идёт на следующем
 * контроллере.
 *
 * Возвращает 1, если "usb0" зарегистрирован. Никогда не зависает: все
 * ожидания ограничены по времени. */
int usb_init(int (*accept)(blockdev_t* dev));

#endif /* USB_H */
